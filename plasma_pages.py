"""Pure helpers that turn DIQ data into PLASMA pages.

PLASMA (the PARS wiki) keeps its pages in the PARS-DOE/plasma content repo. The DIQ pages live
under `diqs/`, with the same layout and syntax the WikiJS converter gave the imported pages:

    diqs/index.md               every DIQ, by data set (WikiJS `DIQs`)
    diqs/ds01/index.md          one data set's DIQs, by severity (WikiJS `DIQs/DS01`)
    diqs/ds01/1010002.md        one DIQ (WikiJS `DIQs/DS01/1010002`)
    diqs/critical.md            every DIQ of one severity (WikiJS `DIQs/critical`)
    diqs/changelog.md           the changelog (WikiJS `DIQs/changelog`, not generated here)

Pages are Markdown with YAML frontmatter, relative `.md` links, and one `> [!AI]` callout plus
`ai_review: pending` on a page whose AI-written text nobody has reviewed. This module does no I/O
beyond what its callers hand it, and imports nothing that talks to a network.
"""

from __future__ import annotations

import json
import posixpath
import re
from dataclasses import dataclass, field

# ---- Names and paths ----

ROOT = "diqs"
GENERATED_BY = "diq-wiki"

# diq_data.json still uses the old severity names. The wiki shows the new ones.
SEVERITY_LABELS = {
    "ERROR": "CRITICAL",
    "WARNING": "MAJOR",
    "ALERT": "MINOR",
    "CRITICAL": "CRITICAL",
    "MAJOR": "MAJOR",
    "MINOR": "MINOR",
}
SEVERITY_ORDER = ["CRITICAL", "MAJOR", "MINOR"]

BANNER_TEXT = (
    "The following text was generated by an AI tool and hasn't been reviewed for accuracy by a "
    "human! It might be useful, but it also might have errors. Are you a human? You can help by "
    "reviewing it for accuracy! Edit it as needed then remove this message."
)


def clean_segment(segment: str) -> str:
    """One path segment as the WikiJS converter cleans it: lowercase, whitespace to `-`, and
    nothing outside `a-z 0-9 . _ -`."""
    segment = re.sub(r"\s", "-", segment.lower())
    return re.sub(r"[^a-z0-9._-]", "", segment)


def clean_path(path: str) -> str:
    return "/".join(clean_segment(part) for part in path.split("/"))


def severity_label(severity: str) -> str:
    return SEVERITY_LABELS[severity.upper()]


def ds_of(table: str) -> str:
    """`DS01 WBS` -> `DS01`"""
    return table.split(" ")[0]


def root_index_path() -> str:
    return f"{ROOT}/index.md"


def ds_index_path(ds: str) -> str:
    return f"{ROOT}/{clean_segment(ds)}/index.md"


def diq_page_path(ds: str, uid: str) -> str:
    return f"{ROOT}/{clean_segment(ds)}/{clean_segment(str(uid))}.md"


def severity_page_path(severity: str) -> str:
    return f"{ROOT}/{clean_segment(severity_label(severity))}.md"


def wiki_path_to_content_path(wiki_path: str) -> str:
    """A WikiJS DIQ path to its content repo path, as the converter maps it. `DIQs` and
    `DIQs/DSxx` have children, so they become `index.md` pages."""
    parts = wiki_path.strip("/").split("/")
    if parts[0].lower() != "diqs":
        raise ValueError(f"not a DIQ page: {wiki_path}")
    if len(parts) == 1:
        return root_index_path()
    if len(parts) == 2 and re.fullmatch(r"(?i)ds\d\d", parts[1]):
        return ds_index_path(parts[1])
    return clean_path("/".join([ROOT, *parts[1:]])) + ".md"


def relative_link(source: str, target: str) -> str:
    """The relative link from the page at `source` to the file at `target` (both repo paths)."""
    return posixpath.relpath(target, posixpath.dirname(source) or ".")


# PLASMA's filename rules for the paths this tool writes
_WINDOWS_RESERVED = re.compile(r"^(con|prn|aux|nul|com[1-9]|lpt[1-9])(\..*)?$")


def path_problem(path: str) -> str | None:
    """Why PLASMA would refuse this path, or None."""
    for part in path.split("/"):
        if not re.fullmatch(r"[a-z0-9._-]+", part):
            return f"{path}: names must be lowercase ASCII letters, digits, '.', '_' or '-'"
        if part.endswith(".") or _WINDOWS_RESERVED.match(part):
            return f"{path}: '{part}' is not a usable name"
    return None


def page_clashes(paths) -> list[str]:
    """`x.md` beside `x/index.md` is not allowed."""
    found = set(paths)
    return sorted(
        p for p in found if p.endswith(".md") and not p.endswith("/index.md")
        and f"{p[:-3]}/index.md" in found
    )


# ---- Frontmatter ----

# The converter's field order. Fields not listed keep their place after these.
FIELD_ORDER = [
    "title", "description", "tags", "created", "modified", "status", "generated_by",
    "ai_review", "math",
]
# The fields a regeneration decides. Every other field of an existing page is kept as it is.
OWNED_FIELDS = {"title", "description", "tags", "status", "generated_by", "ai_review"}

_YAML_NUMBER = re.compile(r"[-+]?(\.\d+|\d[\d_]*(\.\d*)?)([eE][-+]?\d+)?|0x[0-9a-fA-F]+|0o[0-7]+")
_YAML_WORDS = {"true", "false", "null", "~", ".nan", ".inf", "-.inf", "+.inf", "yes", "no", "on", "off"}


def yaml_scalar(value: str) -> str:
    """A string as YAML writes it: plain where that reads back as the same string, else in
    double quotes (as the converter's `yaml` library does)."""
    plain = (
        value != ""
        and value == value.strip()
        and "\n" not in value
        and value[0] not in "-?:,[]{}#&*!|>'\"%@`"
        and ": " not in value
        and " #" not in value
        and not value.endswith(":")
        and value.lower() not in _YAML_WORDS
        and not _YAML_NUMBER.fullmatch(value)
    )
    return value if plain else json.dumps(value, ensure_ascii=False)


def field_block(key: str, value) -> str:
    """One frontmatter field, as the lines it takes (ending in a newline)."""
    if isinstance(value, (list, tuple)):
        return f"{key}:\n" + "".join(f"  - {yaml_scalar(str(item))}\n" for item in value)
    return f"{key}: {yaml_scalar(str(value))}\n"


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    """A page's frontmatter as {field: its raw lines}, in file order, and the body after it. The
    raw lines are kept byte for byte, so fields this tool doesn't own are never rewritten."""
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 3)
    if end < 0:
        if text.endswith("\n---"):
            end = len(text) - 4
        else:
            return {}, text
    block = text[4:end + 1]
    body = text[end + 5:]
    fields: dict[str, str] = {}
    current = None
    for line in block.splitlines(keepends=True):
        match = re.match(r"([A-Za-z_][\w-]*)\s*:", line)
        if match and not line[0].isspace():
            current = match.group(1)
            fields[current] = line
        elif current is not None:
            fields[current] += line
    return fields, body


def assemble(fields: dict[str, str], body: str) -> str:
    """Frontmatter blocks and a body as one file: no blank line after the closing fence, no
    trailing whitespace, one final newline."""
    ordered = [fields[key] for key in FIELD_ORDER if key in fields]
    ordered += [block for key, block in fields.items() if key not in FIELD_ORDER]
    body = body.lstrip("\n").rstrip()
    return "---\n" + "".join(ordered) + "---\n" + body + "\n"


def frontmatter_fields(title, description=None, tags=(), *, created=None, modified=None,
                       ai_review=False) -> dict[str, str]:
    fields = {"title": field_block("title", title)}
    if description and description.strip():
        fields["description"] = field_block("description", description)
    if tags:
        fields["tags"] = field_block("tags", list(tags))
    if created:
        fields["created"] = field_block("created", created)
    if modified:
        fields["modified"] = field_block("modified", modified)
    fields["status"] = field_block("status", "published")
    fields["generated_by"] = field_block("generated_by", GENERATED_BY)
    if ai_review:
        fields["ai_review"] = field_block("ai_review", "pending")
    return fields


@dataclass
class Merge:
    text: str | None  # what to write, or None to leave the file as it is
    state: str  # "new", "changed" or "unchanged"
    ai_review_restored: bool = False  # the page had been reviewed, and this gives it back the flag


def merge_with_existing(generated: str, existing: str | None, now: str) -> Merge:
    """What a regenerated page becomes in the content repo. The generator decides the fields in
    OWNED_FIELDS and the body. Every other field of the existing page (`created`, `author`,
    `math`, ...) is kept as written. `modified` moves to `now` only when something changed."""
    gen_fields, gen_body = split_frontmatter(generated)
    if existing is None:
        gen_fields.setdefault("created", field_block("created", now))
        gen_fields["modified"] = field_block("modified", now)
        return Merge(assemble(gen_fields, gen_body), "new")

    old_fields, old_body = split_frontmatter(existing)
    merged = {key: block for key, block in old_fields.items() if key not in OWNED_FIELDS}
    merged.update({key: gen_fields[key] for key in OWNED_FIELDS if key in gen_fields})
    if "created" not in merged and "created" in gen_fields:
        merged["created"] = gen_fields["created"]

    def without_modified(fields):
        return {key: block for key, block in fields.items() if key != "modified"}

    candidate = assemble(without_modified(merged), gen_body)
    if candidate == assemble(without_modified(old_fields), old_body):
        return Merge(None, "unchanged")
    merged["modified"] = field_block("modified", now)
    return Merge(
        assemble(merged, gen_body),
        "changed",
        ai_review_restored="ai_review" in merged and "ai_review" not in old_fields,
    )


# ---- Body text ----

_FENCE = re.compile(r"^ {0,3}(`{3,}|~{3,})")
_CALLOUT_MARKER = re.compile(r"^\{\.is-(info|success|warning|danger)\}\s*$")
_CALLOUT_KINDS = {"info": "NOTE", "success": "TIP", "warning": "WARNING", "danger": "CAUTION"}


def _is_banner(text: str) -> bool:
    return bool(re.search(r"generated by an AI tool", text, re.I)) and bool(
        re.search(r"hasn['’]t been reviewed", text, re.I)
    )


def _outside_code(lines):
    """Yields (index, line, in_code) for each line."""
    fence = None
    for index, line in enumerate(lines):
        match = _FENCE.match(line)
        if fence is None and match:
            fence = match.group(1)[0] * 3
            yield index, line, True
        elif fence is not None:
            if line.strip().startswith(fence) and line.strip().strip(fence[0]) == "":
                fence = None
            yield index, line, True
        else:
            yield index, line, False


def strip_ai_banners(text: str) -> tuple[str, bool]:
    """Takes out every AI banner, WikiJS's (`> :robot: ...` plus `{.is-warning}`) and PLASMA's
    (`> [!AI]` and its lines), and closes the gap a removal leaves as the converter does.
    Returns the text and whether any banner was found."""
    lines = text.split("\n")
    code = {i for i, _line, in_code in _outside_code(lines) if in_code}
    out: list[str] = []
    removed_at: list[int] = []
    found = False
    i = 0
    while i < len(lines):
        if i not in code and lines[i].startswith(">"):
            j = i
            while j < len(lines) and j not in code and lines[j].startswith(">"):
                j += 1
            quote = "\n".join(lines[i:j])
            if lines[i].strip() == "> [!AI]" or _is_banner(quote):
                found = True
                if j < len(lines) and _CALLOUT_MARKER.match(lines[j]):
                    j += 1
                removed_at.append(len(out))
                i = j
                continue
            out.extend(lines[i:j])
            i = j
            continue
        out.append(lines[i])
        i += 1
    # Close the gaps, last first so earlier positions stay right
    for at in reversed(removed_at):
        if at == 0:
            while out and out[0].strip() == "":
                out.pop(0)
        else:
            while at < len(out) and at > 0 and out[at - 1].strip() == "" and out[at].strip() == "":
                out.pop(at)
    return "\n".join(out), found


def convert_callouts(text: str) -> str:
    """WikiJS's `> text` + `{.is-warning}` callouts as PLASMA's `> [!WARNING]` ones."""
    lines = text.split("\n")
    code = {i for i, _line, in_code in _outside_code(lines) if in_code}
    out: list[str] = []
    for i, line in enumerate(lines):
        match = _CALLOUT_MARKER.match(line) if i not in code else None
        if match and out and out[-1].startswith(">"):
            start = len(out)
            while start > 0 and out[start - 1].startswith(">"):
                start -= 1
            out.insert(start, f"> [!{_CALLOUT_KINDS[match.group(1)]}]")
            continue
        out.append(line)
    return "\n".join(out)


def ai_callout() -> str:
    return "> [!AI]\n> " + BANNER_TEXT


def with_ai_callout(body: str) -> str:
    """Puts the `[!AI]` callout under a leading H1, else at the very top."""
    body = body.lstrip("\n")
    first, _, rest = body.partition("\n")
    if re.match(r"# \S", first):
        rest = rest.lstrip("\n")
        return f"{first}\n\n{ai_callout()}\n\n{rest}"
    return f"{ai_callout()}\n\n{body}"


def split_sections(body: str) -> tuple[str, list[tuple[str, str]]]:
    """A body as the text before its first `## ` heading, and (heading, text) pairs. The heading
    is the title without `## `. Each text runs from after the heading's line to the next
    heading, exactly as written."""
    lines = body.split("\n")
    starts = [
        i for i, line, in_code in _outside_code(lines) if not in_code and line.startswith("## ")
    ]
    if not starts:
        return body, []
    preamble = "\n".join(lines[: starts[0]])
    sections = []
    for n, start in enumerate(starts):
        end = starts[n + 1] if n + 1 < len(starts) else len(lines)
        sections.append((lines[start][3:].strip(), "\n".join(lines[start + 1: end])))
    return preamble, sections


def escape_cell(text: str) -> str:
    return str(text).replace("\n", " ").replace("|", "\\|").strip()


def md_table(header: list[str], rows: list[list[str]]) -> str:
    """A table padded as prettier pads it (the existing pages were formatted so)."""
    widths = [max(3, len(h), *(len(row[i]) for row in rows)) for i, h in enumerate(header)]

    def line(cells):
        return "| " + " | ".join(cell.ljust(width) for cell, width in zip(cells, widths)) + " |"

    return "\n".join([line(header), line(["-" * w for w in widths]), *map(line, rows)])


# ---- Pages ----

PROSE_SECTIONS = ("What causes this error?", "Why do we check this?")
OWNED_SECTIONS = ("Basic Information", *PROSE_SECTIONS, "Code")


@dataclass
class Diq:
    uid: str
    table: str
    severity: str  # as the wiki shows it: CRITICAL, MAJOR or MINOR
    title: str
    summary: str
    message: str

    @property
    def ds(self) -> str:
        return ds_of(self.table)

    @property
    def path(self) -> str:
        return diq_page_path(self.ds, self.uid)


def diq_from_data(name: str, entry: dict) -> Diq | None:
    """One diq_data.json entry, or None for one that has no page (deleted, or without a UID)."""
    if entry.get("status") in ("DELETED", "DELETE") or not entry.get("UID"):
        return None
    return Diq(
        uid=str(entry["UID"]),
        table=entry["table"],
        severity=severity_label(entry["severity"]),
        title=entry["title"],
        summary=entry.get("summary", ""),
        message=entry.get("message", ""),
    )


@dataclass
class Reused:
    """What a regeneration keeps from the page as it stands: the prose people may have edited,
    any section the generator doesn't write, and what follows the SQL in the Code section."""
    preamble: str = ""
    prose: dict[str, str] = field(default_factory=dict)
    extra_sections: list[tuple[str, str]] = field(default_factory=list)  # (heading, text), after the prose
    code_tail: str = ""
    ai_pending: bool = False


def read_existing_diq_page(text: str) -> Reused:
    """Reads a DIQ page as it stands, in WikiJS syntax or PLASMA's."""
    _fields, body = split_frontmatter(text)
    body, banner = strip_ai_banners(body)
    preamble, sections = split_sections(body)
    reused = Reused(preamble=preamble, ai_pending=banner)
    for heading, section_text in sections:
        if heading in PROSE_SECTIONS:
            reused.prose[heading] = section_text
        elif heading == "Code":
            lines = section_text.split("\n")
            fences = [i for i, line in enumerate(lines) if _FENCE.match(line)]
            if len(fences) >= 2:
                reused.code_tail = "\n".join(lines[fences[1] + 1:])
        elif heading != "Basic Information":
            reused.extra_sections.append((heading, section_text))
    return reused


def strip_sql_comments(sql: str) -> str:
    """The SQL as the pages show it: blank lines dropped, `/* ... */` comments removed."""
    sql = "".join(line for line in sql.splitlines(keepends=True) if line.strip() != "")
    return re.sub(r"/\*.*?\*/", "", sql, flags=re.DOTALL)


def render_diq_body(diq: Diq, sql: str, prose: dict[str, str], *, ai_pending: bool,
                    reused: Reused | None = None) -> str:
    """The body of one DIQ page. `prose` maps each of PROSE_SECTIONS to its text: either a
    section's text as it stands on the page (from `read_existing_diq_page`), or a fresh
    explanation (from `fresh_prose`)."""
    reused = reused or Reused()
    parts = []
    if reused.preamble.strip():
        parts.append(convert_callouts(reused.preamble.strip("\n")) + "\n\n")
    parts.append("## Basic Information\n")
    parts.append("| Key         | Value          |\n|-------------|----------------|\n")
    parts.append(f"| Table       | {escape_cell(diq.table)} |\n")
    parts.append(f"| Severity    | {diq.severity} |\n")
    parts.append(f"| Unique ID   | {diq.uid}   |\n")
    parts.append(f"| Summary     | {escape_cell(diq.summary)} |\n")
    parts.append(f"| Error message | {escape_cell(diq.message)} |\n\n")
    for heading in PROSE_SECTIONS:
        parts.append(f"## {heading}\n{prose[heading]}\n")
    for heading, text in reused.extra_sections:
        parts.append(f"## {heading}\n{convert_callouts(text)}\n")
    parts.append("## Code\n\n```sql\n" + sql + "\n```\n" + convert_callouts(reused.code_tail))
    body = "".join(parts)
    return with_ai_callout(body) if ai_pending else body


def fresh_prose(text: str) -> str:
    """A fresh explanation as a section's text: a blank line after the heading, then the text."""
    return "\n" + text.strip("\n")


def render_diq_page(diq: Diq, body: str, *, ai_pending: bool) -> str:
    fields = frontmatter_fields(
        diq.title, diq.summary, [f"severity: {diq.severity.lower()}", diq.ds.lower()],
        ai_review=ai_pending,
    )
    return assemble(fields, body)


def _diq_row(diq: Diq, source: str, *, with_severity: bool) -> list[str]:
    row = [f"[{diq.uid}]({relative_link(source, diq.path)})", escape_cell(diq.title)]
    if with_severity:
        row.append(f"[{diq.severity}]({relative_link(source, severity_page_path(diq.severity))})")
    return row + [escape_cell(diq.summary), escape_cell(diq.message)]


def _by_severity_then_uid(diq: Diq):
    return (SEVERITY_ORDER.index(diq.severity), diq.uid)


def render_ds_index(ds: str, diqs: list[Diq], preamble: str = "") -> str:
    """`diqs/dsNN/index.md`: one table for each severity."""
    source = ds_index_path(ds)
    parts = [convert_callouts(preamble.strip("\n"))] if preamble.strip() else []
    for severity in SEVERITY_ORDER:
        rows = [_diq_row(d, source, with_severity=False)
                for d in sorted(diqs, key=lambda d: d.uid) if d.severity == severity]
        if rows:
            parts.append(f"## {severity}\n\n" + md_table(["UID", "Title", "Summary", "Error Message"], rows))
    return assemble(frontmatter_fields(ds), "\n\n".join(parts))


def render_root_index(by_ds: dict[str, list[Diq]], preamble: str = "") -> str:
    """`diqs/index.md`: every DIQ, one table for each data set."""
    source = root_index_path()
    parts = [convert_callouts(preamble.strip("\n"))] if preamble.strip() else []
    for ds in sorted(by_ds):
        rows = [_diq_row(d, source, with_severity=True)
                for d in sorted(by_ds[ds], key=_by_severity_then_uid)]
        parts.append(
            f"## [{ds}]({relative_link(source, ds_index_path(ds))})\n\n"
            + md_table(["UID", "Title", "Severity", "Summary", "Error Message"], rows)
        )
    return assemble(frontmatter_fields("DIQs"), "\n\n".join(parts))


def render_severity_page(severity: str, by_ds: dict[str, list[Diq]]) -> str:
    """`diqs/critical.md` and the others: one table for each data set."""
    severity = severity_label(severity)
    source = severity_page_path(severity)
    parts = []
    for ds in sorted(by_ds):
        rows = [_diq_row(d, source, with_severity=False)
                for d in sorted(by_ds[ds], key=lambda d: d.uid) if d.severity == severity]
        if rows:
            parts.append(f"## {ds}\n\n" + md_table(["UID", "Title", "Summary", "Error Message"], rows))
    return assemble(frontmatter_fields(f"{severity} DIQs"), "\n\n".join(parts))


def group_by_ds(diqs) -> dict[str, list[Diq]]:
    by_ds: dict[str, list[Diq]] = {}
    for diq in diqs:
        by_ds.setdefault(diq.ds, []).append(diq)
    return by_ds


def index_pages(diqs, preambles: dict[str, str] | None = None) -> dict[str, str]:
    """Every index and severity page, as {content repo path: text}. `preambles` holds the text
    before the first heading of an existing index page, which is kept."""
    preambles = preambles or {}
    by_ds = group_by_ds(diqs)
    pages = {root_index_path(): render_root_index(by_ds, preambles.get(root_index_path(), ""))}
    for ds, members in by_ds.items():
        path = ds_index_path(ds)
        pages[path] = render_ds_index(ds, members, preambles.get(path, ""))
    for severity in SEVERITY_ORDER:
        pages[severity_page_path(severity)] = render_severity_page(severity, by_ds)
    return pages
