"""Path mapping and page output for PLASMA. No network, database or keys."""

import json
import os

import pytest
import yaml

import generateMarkdown
import plasma_pages as pp
import publishToPlasma

NOW = "2026-11-16T12:00:00Z"
DIQ = pp.Diq(uid="1010002", table="DS01 WBS", severity="CRITICAL", title="WBS Level Contiguity",
             summary="Are the WBS Levels contiguous?", message="Level a | b is not contiguous.")


def frontmatter(text):
    assert text.startswith("---\n")
    return yaml.safe_load(text.split("---\n")[1])


# ---- Paths ----

@pytest.mark.parametrize("wiki, content", [
    ("DIQs", "diqs/index.md"),
    ("DIQs/DS01", "diqs/ds01/index.md"),
    ("DIQs/DS01/1010002", "diqs/ds01/1010002.md"),
    ("DIQs/critical", "diqs/critical.md"),
])
def test_wiki_paths_map_to_lowercase_content_paths(wiki, content):
    assert pp.wiki_path_to_content_path(wiki) == content


def test_page_paths():
    assert DIQ.path == "diqs/ds01/1010002.md"
    assert pp.ds_index_path("DS01") == "diqs/ds01/index.md"
    assert pp.root_index_path() == "diqs/index.md"
    assert pp.severity_page_path("ERROR") == "diqs/critical.md"


def test_clean_path_lowercases_and_strips_what_plasma_refuses():
    assert pp.clean_path("DIQs/DS 01/A&B.md") == "diqs/ds-01/ab.md"


@pytest.mark.parametrize("old, new", [("ERROR", "CRITICAL"), ("WARNING", "MAJOR"),
                                      ("ALERT", "MINOR"), ("critical", "CRITICAL")])
def test_severity_labels(old, new):
    assert pp.severity_label(old) == new


def test_relative_links():
    assert pp.relative_link("diqs/index.md", "diqs/ds01/1010002.md") == "ds01/1010002.md"
    assert pp.relative_link("diqs/ds01/index.md", "diqs/ds01/1010002.md") == "1010002.md"
    assert pp.relative_link("diqs/ds01/index.md", "diqs/critical.md") == "../critical.md"


def test_path_rules():
    assert pp.path_problem("diqs/ds01/1010002.md") is None
    assert pp.path_problem("diqs/DS01/x.md")
    assert pp.path_problem("diqs/con.md")
    assert pp.page_clashes(["diqs/ds01.md", "diqs/ds01/index.md", "diqs/x.md"]) == ["diqs/ds01.md"]


# ---- Frontmatter ----

def test_yaml_scalars_are_quoted_only_when_needed():
    assert pp.yaml_scalar("ds01") == "ds01"
    assert pp.yaml_scalar("severity: critical") == '"severity: critical"'
    assert pp.yaml_scalar("123") == '"123"'
    assert pp.yaml_scalar("yes") == '"yes"'
    for value in ["a: b", "#x", "- y", "it's", 'say "hi"', "1e3", "null"]:
        assert yaml.safe_load(f"k: {pp.yaml_scalar(value)}")["k"] == value


def test_diq_page_frontmatter_matches_the_converter():
    text = pp.render_diq_page(DIQ, "body\n", ai_pending=True)
    assert text.startswith(
        "---\ntitle: WBS Level Contiguity\ndescription: Are the WBS Levels contiguous?\n"
        'tags:\n  - "severity: critical"\n  - ds01\nstatus: published\n'
        "generated_by: diq-wiki\nai_review: pending\n---\nbody\n"
    )
    assert "ai_review" not in pp.render_diq_page(DIQ, "body\n", ai_pending=False)


# ---- Body ----

BANNER = ("> :robot: The following text was generated by an AI tool and hasn't been reviewed for "
          "accuracy by a human! It might be useful, but it also might have errors.\n{.is-warning}")


def test_wikijs_banner_becomes_one_ai_callout():
    page = ("## Basic Information\n| Key | Value |\n\n## What causes this error?\n\n" + BANNER
            + "\n\nIt is caused.\n## Why do we check this?\n\nBecause.\n## Code\n\n```sql\nSELECT 1\n```\n")
    reused = pp.read_existing_diq_page(page)
    assert reused.ai_pending
    assert reused.prose["What causes this error?"] == "\nIt is caused."
    body = pp.render_diq_body(DIQ, "SELECT 1", reused.prose, ai_pending=True, reused=reused)
    assert body.startswith("> [!AI]\n> The following text was generated by an AI tool")
    assert ":robot:" not in body and "{.is-" not in body
    assert body.count("[!AI]") == 1


def test_ai_callout_goes_under_a_leading_h1():
    assert pp.with_ai_callout("# Title\n\ntext").startswith("# Title\n\n> [!AI]\n")


def test_callout_markers_become_github_callouts():
    text = "> Please note this.\n> Second line.\n{.is-warning}\n\n> Info\n{.is-info}"
    assert pp.convert_callouts(text) == (
        "> [!WARNING]\n> Please note this.\n> Second line.\n\n> [!NOTE]\n> Info"
    )


def test_markers_inside_code_are_left_alone():
    text = "```\n> quoted\n{.is-danger}\n```"
    assert pp.convert_callouts(text) == text


def test_diq_body_layout_and_escaped_pipes():
    prose = {h: pp.fresh_prose(f"About {h}") for h in pp.PROSE_SECTIONS}
